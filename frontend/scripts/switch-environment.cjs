#!/usr/bin/env node
/**
 * Environment Switching Script
 * Switches between local and production environments
 * Cross-platform compatible (Windows, Mac, Linux)
 */

const fs = require('fs');
const path = require('path');

// ANSI color codes
const colors = {
  reset: '\x1b[0m',
  bright: '\x1b[1m',
  red: '\x1b[31m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  cyan: '\x1b[36m'
};

function log(message, color = 'reset') {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

// Environment configurations
const ENVIRONMENTS = {
  local: {
    name: 'Local Development',
    VITE_API_BASE_URL: 'http://localhost:8787',
    VITE_WS_URL: 'ws://localhost:8787',
    VITE_ENVIRONMENT: 'development'
  },
  prod: {
    name: 'Production',
    VITE_API_BASE_URL: 'https://mcis-backend.daiwandist.com',
    VITE_WS_URL: 'wss://mcis-backend.daiwandist.com',
    VITE_ENVIRONMENT: 'production'
  },
  remote: {
    name: 'Remote Development',
    VITE_API_BASE_URL: 'https://mcis-backend.daiwandist.com',
    VITE_WS_URL: 'wss://mcis-backend.daiwandist.com',
    VITE_ENVIRONMENT: 'development'
  }
};

function switchEnvironment(targetEnv) {
  const config = ENVIRONMENTS[targetEnv];

  if (!config) {
    log(`\n❌ Unknown environment: ${targetEnv}`, 'red');
    log(`   Available: ${Object.keys(ENVIRONMENTS).join(', ')}`, 'yellow');
    process.exit(1);
  }

  console.log();
  log('╔═══════════════════════════════════════════════════════════════╗', 'cyan');
  log('║       🔄 Environment Switch Script                            ║', 'bright');
  log('╚═══════════════════════════════════════════════════════════════╝', 'cyan');

  log(`\n📍 Switching to: ${config.name}`, 'yellow');

  // Find frontend directory
  const scriptDir = __dirname;
  const frontendDir = path.dirname(scriptDir);
  const envLocalPath = path.join(frontendDir, '.env.local');

  // Generate .env.local content
  const envContent = `# Auto-generated by switch-environment.cjs
# Environment: ${config.name}
# Generated: ${new Date().toISOString()}

VITE_API_BASE_URL=${config.VITE_API_BASE_URL}
VITE_WS_URL=${config.VITE_WS_URL}
VITE_ENVIRONMENT=${config.VITE_ENVIRONMENT}
`;

  try {
    // Backup existing .env.local if it exists
    if (fs.existsSync(envLocalPath)) {
      const backupPath = `${envLocalPath}.backup`;
      fs.copyFileSync(envLocalPath, backupPath);
      log(`\n📦 Backed up existing .env.local`, 'blue');
    }

    // Write new .env.local
    fs.writeFileSync(envLocalPath, envContent, 'utf8');

    log('\n════════════════════════════════════════════════════════════', 'blue');
    log('  Configuration Applied', 'cyan');
    log('════════════════════════════════════════════════════════════', 'blue');

    log(`  ✅ API URL:     ${config.VITE_API_BASE_URL}`, 'green');
    log(`  ✅ WebSocket:   ${config.VITE_WS_URL}`, 'green');
    log(`  ✅ Environment: ${config.VITE_ENVIRONMENT}`, 'green');

    console.log();
    log('╔═══════════════════════════════════════════════════════════════╗', 'green');
    log(`║  🎉 Successfully switched to ${config.name.padEnd(27)}║`, 'green');
    log('╚═══════════════════════════════════════════════════════════════╝', 'green');

    log('\n💡 Tip: Restart your dev server for changes to take effect', 'yellow');
    log('   Run: npm run dev\n', 'blue');

  } catch (error) {
    log(`\n❌ Failed to write .env.local: ${error.message}`, 'red');
    process.exit(1);
  }
}

// Parse command line arguments
const args = process.argv.slice(2);
let targetEnv = args[0] || 'local';

// Handle common variations
const envMap = {
  'local': 'local',
  'development': 'local',
  'dev': 'local',
  'prod': 'prod',
  'production': 'prod',
  'remote': 'remote'
};

targetEnv = envMap[targetEnv.toLowerCase()] || targetEnv;

// Run switch
switchEnvironment(targetEnv);
